import assert from "node:assert/strict";
import test from "node:test";
import {DatabaseSync} from "node:sqlite";
import {validate} from "../app/core-record-validation";
import {coreWriteGuard} from "../app/core-reference-write";
import {editableEvidence,evidenceReviewerIsIndependent,pendingEvidence,validityDate} from "../app/evidence/intake";
import {canWriteModule,scopedApiAllowed} from "../app/module-access";
const metadata={evidenceTitle:"Access review",controlRef:"CTL-325",owner:"holder@example.org",period:"2026-Q4"};
test("intake protects version anchors and review decisions across register/import writes",()=>{
  const created=validate("Kanıtlar",{...metadata,status:"Onaylandı",reviewStatus:"approved",fileKey:"untrusted",reviewedBy:"other"});
  assert.deepEqual(created.data,{...metadata,...pendingEvidence});
  const before={...metadata,reviewer:"reviewer@example.org",fileKey:"verified",uploadedBy:"uploader@example.org",versionNo:"2",reviewedBy:"peer",reviewedVersion:"version-2",status:"Onaylandı",reviewStatus:"approved"};
  const changed=editableEvidence({...before,notes:"Changed context",fileKey:"other",uploadedBy:"spoof"},before);
  assert.equal(changed.fileKey,"verified");assert.equal(changed.uploadedBy,before.uploadedBy);
  assert.equal(changed.status,"İncelemede");assert.equal(changed.reviewedVersion,undefined);
  assert.deepEqual(editableEvidence(before,before),before);
  assert.equal(evidenceReviewerIsIndependent(before,{email:metadata.owner}),false);
  for(const value of [metadata.owner,before.uploadedBy,"latest@example.org"])assert.equal(evidenceReviewerIsIndependent({...before,reviewer:value},{email:value},["latest@example.org"]),false);
  assert.equal(evidenceReviewerIsIndependent(before,{email:before.reviewer}),true);
  assert.ok(validate("Kanıtlar",{...metadata,reviewer:metadata.owner}).error);
  assert.ok(validate("Kanıtlar",{...metadata,collectedAt:"2026-09-03",expiresAt:"2026-09-02"}).error);
  assert.equal(validityDate("2028-08-31","6m"),"2029-02-28");assert.equal(validityDate("2028-02-29","1y"),"2029-02-28");assert.equal(validityDate("2028-02-29","30"),"2028-03-30");assert.equal(validityDate("2026-11-23","90"),"2027-02-21");
});
test("assignment guard checks the active directory, reviewer write access and legacy owner names",()=>{
  const db=new DatabaseSync(":memory:");
  db.exec("CREATE TABLE local_users(id TEXT,name TEXT,email TEXT,status TEXT,role TEXT);CREATE TABLE user_module_access(user_id TEXT,policy_json TEXT)");
  db.prepare("INSERT INTO local_users VALUES(?,?,?,?,?)").run("r","GRC Reviewer","reviewer@example.org","Active","Editor");
  const ok=(owner:string)=>{const guard=coreWriteGuard("Kanıtlar",[{id:"e",data:{owner,reviewer:"reviewer@example.org"}}]);return Boolean(db.prepare("SELECT 1 WHERE "+guard.sql).get(...guard.values))};
  assert.equal(ok("GRC Reviewer"),false);assert.equal(ok("Evidence Owner"),true);
  db.prepare("INSERT INTO user_module_access VALUES(?,?)").run("r",JSON.stringify({mode:"scoped",modules:{"Kanıtlar":"read"}}));assert.equal(ok("Evidence Owner"),false);
  db.exec("UPDATE local_users SET status='Disabled'");assert.equal(ok("Evidence Owner"),false);
  const viewer={role:"Viewer",moduleAccess:{mode:"scoped" as const,modules:{Kanıtlar:"read" as const}}};
  assert.equal(scopedApiAllowed(viewer,"/api/evidence/review","POST"),false);assert.equal(canWriteModule(viewer,"Kanıtlar"),false);
});
